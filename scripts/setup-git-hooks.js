#!/usr/bin/env node

/**
 * 🔧 Git Hooks Setup Script
 * 
 * Installs pre-commit hook for secret detection.
 * Run: npm run setup:git-hooks
 * 
 * @author Consciousness Revolution Platform Team
 * @version 1.0.0
 */

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

// Terminal colors
const colors = {
    reset: '\x1b[0m',
    green: '\x1b[32m',
    yellow: '\x1b[33m',
    cyan: '\x1b[36m',
};

const projectRoot = path.resolve(__dirname, '..');
const gitHooksDir = path.join(projectRoot, '.git', 'hooks');
const preCommitHook = path.join(gitHooksDir, 'pre-commit');
const preCommitScript = path.join(projectRoot, 'scripts', 'pre-commit-hook.js');

console.log(`${colors.cyan}🔧 Setting up Git hooks...${colors.reset}\n`);

// Check if .git directory exists
if (!fs.existsSync(path.join(projectRoot, '.git'))) {
    console.log(`${colors.yellow}⚠️  Not a git repository. Skipping hook installation.${colors.reset}\n`);
    process.exit(0);
}

// Create hooks directory if it doesn't exist
if (!fs.existsSync(gitHooksDir)) {
    fs.mkdirSync(gitHooksDir, { recursive: true });
}

// Check if pre-commit hook already exists
if (fs.existsSync(preCommitHook)) {
    console.log(`${colors.yellow}⚠️  Pre-commit hook already exists${colors.reset}`);
    const content = fs.readFileSync(preCommitHook, 'utf8');
    
    if (content.includes('pre-commit-hook.js')) {
        console.log(`${colors.green}✓ Secret detection hook is already installed${colors.reset}\n`);
        process.exit(0);
    }
    
    // Backup existing hook
    const backupPath = preCommitHook + '.backup';
    fs.copyFileSync(preCommitHook, backupPath);
    console.log(`${colors.cyan}ℹ  Backed up existing hook to: ${backupPath}${colors.reset}\n`);
}

// Create the pre-commit hook
const hookContent = `#!/bin/sh
#
# Pre-commit hook for Consciousness Revolution
# Auto-generated by setup-git-hooks.js
#
# This hook runs secret detection before allowing a commit.
# To bypass: git commit --no-verify (NOT recommended)
#

node scripts/pre-commit-hook.js
`;

try {
    fs.writeFileSync(preCommitHook, hookContent, { mode: 0o755 });
    
    // Set executable permissions (Unix-like systems)
    if (process.platform !== 'win32') {
        fs.chmodSync(preCommitHook, 0o755);
    }
    
    console.log(`${colors.green}✓ Pre-commit hook installed successfully${colors.reset}`);
    console.log(`${colors.cyan}  Location: ${preCommitHook}${colors.reset}\n`);
    
    console.log(`${colors.cyan}What this does:${colors.reset}`);
    console.log(`  • Scans staged files for exposed API keys before commit`);
    console.log(`  • Blocks commits that contain potential secrets`);
    console.log(`  • Helps prevent accidental credential exposure\n`);
    
    console.log(`${colors.cyan}Testing the hook:${colors.reset}`);
    console.log(`  Try running: node scripts/pre-commit-hook.js\n`);
    
    console.log(`${colors.green}🎉 Setup complete!${colors.reset}\n`);
    
} catch (error) {
    console.error(`${colors.red}❌ Failed to install hook: ${error.message}${colors.reset}\n`);
    process.exit(1);
}
