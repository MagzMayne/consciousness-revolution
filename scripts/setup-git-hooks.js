#!/usr/bin/env node

/**
 * Git Hooks Setup Script
 * 
 * This script installs pre-commit hooks for secret detection.
 * The hook will automatically scan staged files for exposed secrets
 * before allowing a commit.
 * 
 * Usage: npm run setup:git-hooks
 */

const fs = require('fs');
const path = require('path');

// ANSI color codes
const colors = {
    reset: '\x1b[0m',
    bright: '\x1b[1m',
    green: '\x1b[32m',
    yellow: '\x1b[33m',
    blue: '\x1b[34m',
    red: '\x1b[31m',
    cyan: '\x1b[36m',
};

function log(message, color = 'reset') {
    console.log(`${colors[color]}${message}${colors.reset}`);
}

function main() {
    log('\n╔════════════════════════════════════════════════════════════╗', 'cyan');
    log('║              🔧 Git Hooks Installation                      ║', 'cyan');
    log('╚════════════════════════════════════════════════════════════╝\n', 'cyan');
    
    // Check if we're in a git repository
    const gitDir = path.join(process.cwd(), '.git');
    if (!fs.existsSync(gitDir)) {
        log('❌ Not a git repository!', 'red');
        log('   Initialize git first: git init\n', 'yellow');
        process.exit(1);
    }
    
    // Create hooks directory if it doesn't exist
    const hooksDir = path.join(gitDir, 'hooks');
    if (!fs.existsSync(hooksDir)) {
        log('📁 Creating hooks directory...', 'blue');
        fs.mkdirSync(hooksDir, { recursive: true });
        log('   ✅ Hooks directory created', 'green');
    }
    
    // Create pre-commit hook
    log('\n🔒 Installing pre-commit secret detection hook...', 'blue');
    const hookPath = path.join(hooksDir, 'pre-commit');
    
    // Check if hook already exists
    if (fs.existsSync(hookPath)) {
        log('   ⚠️  Pre-commit hook already exists', 'yellow');
        const readline = require('readline').createInterface({
            input: process.stdin,
            output: process.stdout
        });
        
        readline.question('   Overwrite existing hook? (y/N): ', (answer) => {
            readline.close();
            if (answer.toLowerCase() !== 'y') {
                log('   ❌ Installation cancelled\n', 'yellow');
                process.exit(0);
            }
            installHook(hookPath);
        });
    } else {
        installHook(hookPath);
    }
}

function installHook(hookPath) {
    // Create the hook content
    const hookContent = `#!/bin/sh
#
# Pre-commit hook for secret detection
# Auto-generated by npm run setup:git-hooks
# 

# Run the secret detection script
node scripts/pre-commit-hook.js

# Capture the exit code
EXIT_CODE=$?

# If secrets were found, prevent the commit
if [ $EXIT_CODE -ne 0 ]; then
    exit 1
fi

# All clear, allow the commit
exit 0
`;
    
    try {
        // Write the hook file
        fs.writeFileSync(hookPath, hookContent);
        log('   ✅ Pre-commit hook created', 'green');
        
        // Make the hook executable
        fs.chmodSync(hookPath, 0o755);
        log('   ✅ Hook made executable', 'green');
        
        // Summary
        log('\n╔════════════════════════════════════════════════════════════╗', 'green');
        log('║              ✨ Git Hooks Installed Successfully! ✨        ║', 'green');
        log('╚════════════════════════════════════════════════════════════╝', 'green');
        
        log('\n🛡️  What was installed:', 'bright');
        log('   ✓  Pre-commit hook for secret detection', 'green');
        log('   ✓  Automatic scanning on every commit', 'green');
        log('   ✓  Protection against exposed API keys', 'green');
        
        log('\n🔍 What gets scanned:', 'bright');
        log('   • OpenAI API keys (sk-*)', 'cyan');
        log('   • GitHub tokens (ghp_*, gho_*, ghu_*)', 'cyan');
        log('   • Anthropic API keys (sk-ant-*)', 'cyan');
        log('   • Groq API keys (gsk_*)', 'cyan');
        log('   • AWS credentials', 'cyan');
        log('   • Database URLs with passwords', 'cyan');
        log('   • Private keys', 'cyan');
        log('   • And more...', 'cyan');
        
        log('\n✅ Next steps:', 'bright');
        log('   1. Try making a commit - the hook will run automatically', 'yellow');
        log('   2. If secrets are detected, the commit will be blocked', 'yellow');
        log('   3. Fix the issues and commit again', 'yellow');
        
        log('\n💡 Tips:', 'bright');
        log('   - Always use .env for secrets (it\'s gitignored)', 'yellow');
        log('   - Use process.env.VARIABLE_NAME in your code', 'yellow');
        log('   - Test and example files are automatically excluded', 'yellow');
        log('   - To bypass (not recommended): git commit --no-verify\n', 'yellow');
        
    } catch (error) {
        log(`\n❌ Failed to install hook: ${error.message}`, 'red');
        process.exit(1);
    }
}

main();
