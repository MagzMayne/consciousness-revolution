// Find relevant tools based on what user is looking for
export function findDomainTools(message) {
    const msgLower = message.toLowerCase();
    const matches = [];

    for (const [domainKey, domain] of Object.entries(DOMAIN_TOOLS)) {
        const keywordMatches = domain.keywords.filter(kw => msgLower.includes(kw));
        if (keywordMatches.length > 0) {
            matches.push({
                domain: domain.name,
                level: domain.level,
                matchedKeywords: keywordMatches,
                tools: domain.tools
            });
        }
    }

    // Sort by most keyword matches
    matches.sort((a, b) => b.matchedKeywords.length - a.matchedKeywords.length);

    return matches;
}

// Format tools for ARAYA's response
export function formatDomainResponse(matches) {
    if (matches.length === 0) {
        return null;
    }

    let response = "Based on what you're looking for, here are some tools that might help:\n\n";

    matches.slice(0, 3).forEach(match => {
        response += `**${match.domain}**\n`;
        match.tools.forEach(tool => {
            response += `• [${tool.name}](${tool.url}) - ${tool.desc}\n`;
        });
        response += '\n';
    });

    return response;
}

