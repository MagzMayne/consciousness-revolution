/**
 * Netlify Function: Health Check
 * Simple health check endpoint to verify Netlify functions are working
 * 
 * Endpoint: /.netlify/functions/health
 * or via redirect: /api/health
 */

exports.handler = async (event, context) => {
  const response = {
    statusCode: 200,
    headers: {
      'Content-Type': 'application/json',
      'Access-Control-Allow-Origin': '*',
      'Access-Control-Allow-Headers': 'Content-Type',
      'Access-Control-Allow-Methods': 'GET, POST, OPTIONS'
    },
    body: JSON.stringify({
      status: 'healthy',
      message: 'Netlify functions are operational',
      timestamp: new Date().toISOString(),
      environment: process.env.CONTEXT || 'unknown',
      repository: 'barbrickdesign.github.io',
      version: '1.0.0',
      auth: Boolean(process.env.GITHUB_TOKEN),
      api_error: null
    })
  };

  return response;
};
